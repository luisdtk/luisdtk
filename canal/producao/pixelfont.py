def text_width(text, scale=1):
    return sum((len(GLYPHS.get(ch, GLYPHS["?"])[0]) + 1) * scale for ch in text.upper()) - scale


def draw_text(draw, x, y, text, color, scale=1, outline=None):
    """Draw text with its top-left at (x, y). outline draws a 1-unit border around every pixel."""
    text = text.upper()
    if outline is not None:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if dx or dy:
                    _draw(draw, x + dx * scale, y + dy * scale, text, outline, scale)
    _draw(draw, x, y, text, color, scale)


def draw_text_centered(draw, cx, y, text, color, scale=1, outline=None):
    draw_text(draw, cx - text_width(text, scale) // 2, y, text, color, scale, outline)


def _draw(draw, x, y, text, color, scale):
    for ch in text:
        g = GLYPHS.get(ch, GLYPHS["?"])
        for r, row in enumerate(g):
            for c, bit in enumerate(row):
                if bit == "1":
                    draw.rectangle((x + c * scale, y + r * scale, x + (c + 1) * scale - 1, y + (r + 1) * scale - 1), fill=color)
        x += (len(g[0]) + 1) * scale
